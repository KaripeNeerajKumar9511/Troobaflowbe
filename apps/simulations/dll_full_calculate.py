def _to_float(value: Any, default: float = 0.0) -> float:
    try:
        return float(value)
    except (TypeError, ValueError):
        return default


def _to_int(value: Any, default: int = 0) -> int:
    try:
        return int(float(value))
    except (TypeError, ValueError):
        return default


def _to_bool(value: Any) -> bool:
    if isinstance(value, bool):
        return value
    if isinstance(value, (int, float)):
        return value != 0
    if isinstance(value, str):
        return value.strip().lower() in {"1", "true", "yes", "y", "on"}
    return False


def _clean_csv_value(value: Any) -> str:
    return str(value).strip() if value is not None else ""


def _read_csv_rows(path: Path) -> List[Dict[str, str]]:
    if not path.exists():
        return []
    with path.open("r", encoding="utf-8", errors="ignore", newline="") as handle:
        reader = csv.DictReader(handle, skipinitialspace=True)
        rows: List[Dict[str, str]] = []
        for row in reader:
            if not row:
                continue
            rows.append({k: _clean_csv_value(v) for k, v in row.items() if k})
        return rows


def _parse_results_err_row(row: str) -> Tuple[str, bool]:
    """
    Parse a results.err CSV row into (message_text, is_warning).
    DLL format: level,In Calculations,<message>, 1 ,<labor>,<equip>,<part>,<op>,<route>,<ibom>
    """
    clean = row.strip()
    if not clean:
        return "", False

    if "in calculations" not in clean.lower():
        lower = clean.lower()
        return clean, lower.startswith("warning") or "warning:" in lower

    parts = [p.strip() for p in clean.split(",")]
    message = ""
    for idx, part in enumerate(parts):
        if part.lower() == "in calculations" and idx + 1 < len(parts):
            message = parts[idx + 1].strip(" -")
            break

    if not message:
        match = re.search(r"In Calculations,\s*(.+?)(?:,\s*\d+\s*,|$)", clean, re.IGNORECASE)
        if match:
            message = match.group(1).strip(" -")

    if not message:
        message = clean

    lower = message.lower()
    is_warning = lower.startswith("warning") or "warning:" in lower
    return message, is_warning


def _read_results_err(path: Path) -> Tuple[List[str], List[str], List[str]]:
    """Return (parsed_errors, parsed_warnings, raw_rows)."""
    if not path.exists():
        return [], [], []

    errors: List[str] = []
    warnings: List[str] = []
    raw: List[str] = []
    with path.open("r", encoding="utf-8", errors="ignore") as handle:
        for idx, line in enumerate(handle):
            clean = line.strip()
            if not clean or idx == 0:
                continue
            raw.append(clean)
            msg, is_warn = _parse_results_err_row(clean)
            if not msg:
                continue
            if is_warn:
                if msg not in warnings:
                    warnings.append(msg)
            elif msg not in errors:
                errors.append(msg)
    return errors, warnings, raw


def _safe_preview(path: Path, max_lines: int = 8) -> List[str]:
    if not path.exists():
        return []
    preview: List[str] = []
    try:
        with path.open("r", encoding="utf-8", errors="ignore") as handle:
            for idx, line in enumerate(handle):
                if idx >= max_lines:
                    break
                preview.append(line.rstrip("\n"))
    except OSError:
        return []
    return preview



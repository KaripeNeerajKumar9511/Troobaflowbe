_DLL_MAX_ATTEMPTS = 6


def _windows_rm_readonly(func, path: str, _exc_info) -> None:
    """Clear read-only bit and retry delete (DLL output files on Windows)."""
    try:
        os.chmod(path, stat.S_IWRITE)
    except OSError:
        pass
    try:
        func(path)
    except OSError:
        pass


def _safe_rmtree(path: Path, *, retries: int = 4, delay_s: float = 0.2) -> None:
    """
    Remove DLL scratch directory without raising.

    tempfile.TemporaryDirectory cleanup can recurse until RecursionError on Windows
    when the native DLL still holds handles or leaves read-only files.
    """
    if not path.exists():
        return
    onerror = _windows_rm_readonly if os.name == "nt" else None
    for attempt in range(retries):
        try:
            shutil.rmtree(path, onerror=onerror)
        except OSError:
            pass
        if not path.exists():
            return
        if attempt < retries - 1:
            time.sleep(delay_s)


def _is_system_warning_message(message: str) -> bool:
    msg = str(message or "").strip().lower()
    if not msg:
        return False
    system_markers = (
        "dll ",
        "dll:",
        "internal error",
        "results.err",
        "routing solver",
        "non-zero code",
        "status code",
        "run_model_from_json",
    )
    return any(marker in msg for marker in system_markers)


def run_full_calculate_via_dll(model: Dict[str, Any], scenario: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
    if not model:
        raise ValueError("Missing 'model' in body")

    model_with_scenario = _apply_scenario(model, scenario)
    _validate_model(model_with_scenario)
    model_for_dll_contract = _convert_model_to_mpx_contract(model_with_scenario)
    payload = _build_dll_model_payload(model_for_dll_contract)
    persisted_input_dir = _persist_input_debug_artifacts(
        model,
        model_with_scenario,
        model_for_dll_contract,
        payload,
    )

    tmp = tempfile.mkdtemp(prefix="rmct_dll_")
    output_root = Path(tmp)
    try:
        attempt_diagnostics: List[Dict[str, Any]] = []
        last_simplified_error = "DLL execution failed."
        last_parsed: Optional[Dict[str, Any]] = None

        for attempt in range(1, _DLL_MAX_ATTEMPTS + 1):
            output_dir = output_root / f"attempt_{attempt}"
            output_dir.mkdir(parents=True, exist_ok=True)
            input_json_path = output_dir / "model_input.json"
            input_json_path.write_text(
                __import__("json").dumps(payload, ensure_ascii=True, indent=2),
                encoding="utf-8",
            )

            try:
                rc, used_mode = run_model_from_json(str(input_json_path), output_dir=str(output_dir), routing_mode="auto")
            except Exception as exc:
                persisted_dir = _persist_failure_artifacts(output_dir)
                attempt_diagnostics.append(
                    {
                        "attempt": attempt,
                        "stage": "run_model_from_json",
                        "inputJsonPath": str(input_json_path),
                        "outputDir": str(output_dir),
                        "persistedInputDir": persisted_input_dir,
                        "persistedOutputDir": persisted_dir,
                        "errorType": type(exc).__name__,
                        "errorMessage": str(exc),
                    }
                )
                last_simplified_error = f"{type(exc).__name__}: {exc}"
                continue

            parsed = _parse_dll_outputs(model_with_scenario, output_dir)
            last_parsed = parsed
            parsed_errors = parsed.get("errors", []) or []
            parsed_warnings = parsed.get("warnings", []) or []
            over_limit_resources = parsed.get("overLimitResources", []) or []
            err_raw_rows = parsed.get("errorsRaw", []) or []
            fatal_error_rows = _has_fatal_error_rows(err_raw_rows)
            system_warnings = [w for w in parsed_warnings if _is_system_warning_message(w)]
            has_retryable_dll_signal = (
                fatal_error_rows
                or bool(parsed_errors)
                or bool(system_warnings)
                or bool(over_limit_resources)
            )

            if has_retryable_dll_signal:
                persisted_dir = _persist_failure_artifacts(output_dir)
                fatal_text = _first_fatal_error_text(err_raw_rows) or (
                    parsed_errors[0] if parsed_errors else None
                )
                simplified_error = fatal_text or (parsed_errors[0] if parsed_errors else None)
                if not simplified_error and system_warnings:
                    simplified_error = system_warnings[0]
                if not simplified_error and over_limit_resources:
                    simplified_error = over_limit_resources[0]
                attempt_diagnostics.append(
                    {
                        "attempt": attempt,
                        "stage": "dll_retryable_signal",
                        "returnCode": rc,
                        "routingModeUsed": used_mode,
                        "inputJsonPath": str(input_json_path),
                        "outputDir": str(output_dir),
                        "persistedInputDir": persisted_input_dir,
                        "resultErrors": parsed_errors,
                        "resultWarnings": parsed_warnings,
                        "overLimitResources": over_limit_resources,
                        "resultsErrPreview": _safe_preview(output_dir / "results.err"),
                        "persistedOutputDir": persisted_dir,
                        "retryReason": (
                            "fatal_results_err_row"
                            if fatal_error_rows
                            else "results_err_rows_present"
                            if parsed_errors
                            else "over_limit_resources_present"
                            if over_limit_resources
                            else "dll_system_warning"
                        ),
                    }
                )
                if simplified_error:
                    last_simplified_error = simplified_error
                else:
                    last_simplified_error = (
                        f"DLL returned non-zero status code: {rc}"
                        if rc != 0
                        else "DLL returned retryable warning/error rows."
                    )
                continue

            # The native DLL often returns rc=-1 (or other non-zero) even when CSV/output parse
            # succeeds and there are no fatal results.err rows — do not surface that as a user warning.
            return _strip_internal_dll_fields(parsed)

        # Retries exhausted: return last DLL-shaped payload so the UI can show the same
        # warnings/errors and numeric tables (zeros where CSV/output was missing).
        if last_parsed is not None:
            return _strip_internal_dll_fields(last_parsed)

        zero_dir = output_root / "_zero_fallback"
        zero_dir.mkdir(parents=True, exist_ok=True)
        final = _parse_dll_outputs(model_with_scenario, zero_dir)
        warn_extra: List[str] = []
        for d in attempt_diagnostics:
            em = d.get("errorMessage")
            if em:
                s = str(em)
                if s not in warn_extra:
                    warn_extra.append(s)
        if not warn_extra and last_simplified_error:
            warn_extra.append(str(last_simplified_error))
        wlist = list(final.get("warnings") or [])
        for s in warn_extra:
            if s not in wlist:
                wlist.append(s)
        final["warnings"] = wlist
        return _strip_internal_dll_fields(final)
    finally:
        _safe_rmtree(output_root)
